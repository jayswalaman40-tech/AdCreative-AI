
import { GoogleGenAI, Type } from "@google/genai";
import { AdCreationFormState } from '../types';

if (!process.env.API_KEY) {
  console.error("API_KEY environment variable not set.");
}

const ai = new GoogleGenAI({ apiKey: process.env.API_KEY as string });

export const generateAdText = async (inputs: AdCreationFormState): Promise<{ headline: string; body: string }[]> => {
  const prompt = `
    You are an expert copywriter. Generate 3 distinct ad copy variations for the following criteria.
    Each variation must have a 'headline' and a 'body'.

    - Ad Platform: ${inputs.platform}
    - Product/Service Name: ${inputs.productName}
    - Target Audience: ${inputs.targetAudience}
    - Offer/Promotion: ${inputs.promotion}
    - Key Selling Points: ${inputs.sellingPoints}
    - Tone of Voice: ${inputs.tone}
    - Call to Action (CTA): ${inputs.cta}

    Return the response as a JSON array of objects.
  `;

  try {
    const response = await ai.models.generateContent({
      model: "gemini-2.5-flash",
      contents: prompt,
      config: {
        responseMimeType: "application/json",
        responseSchema: {
          type: Type.ARRAY,
          items: {
            type: Type.OBJECT,
            properties: {
              headline: {
                type: Type.STRING,
                description: 'A compelling headline for the ad.'
              },
              body: {
                type: Type.STRING,
                description: 'The main body text of the ad.'
              }
            },
            required: ['headline', 'body']
          }
        }
      }
    });

    const jsonString = response.text.trim();
    const parsed = JSON.parse(jsonString);
    if (!Array.isArray(parsed) || parsed.length === 0) {
      throw new Error("AI returned an invalid format.");
    }
    return parsed;
  } catch (error) {
    console.error("Error generating ad text:", error);
    throw new Error("Failed to generate ad copy. Please try again.");
  }
};

export const generateAdImage = async (inputs: AdCreationFormState): Promise<string> => {
  const prompt = `
    Create a compelling, high-quality, photorealistic ad image for a ${inputs.platform} ad.
    The product is "${inputs.productName}".
    The target audience is "${inputs.targetAudience}".
    The overall feeling should be ${inputs.tone}.
    The image should be eye-catching, professional, and suitable for a high-converting digital advertisement. Do not include any text in the image.
  `;

  try {
    const response = await ai.models.generateImages({
      model: 'imagen-4.0-generate-001',
      prompt: prompt,
      config: {
        numberOfImages: 1,
        outputMimeType: 'image/jpeg',
        aspectRatio: '1:1',
      },
    });

    if (response.generatedImages && response.generatedImages.length > 0) {
      return response.generatedImages[0].image.imageBytes;
    } else {
      throw new Error("No image was generated by the API.");
    }
  } catch (error) {
    console.error("Error generating ad image:", error);
    throw new Error("Failed to generate ad image. Please try again.");
  }
};
